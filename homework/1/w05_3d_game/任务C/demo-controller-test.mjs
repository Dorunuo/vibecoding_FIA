import assert from 'node:assert/strict';
import { createDemoController } from '../src/demo.js';
import { GAME_RULES } from '../src/config.js';
let state='PLAYING', treasure='IN_RANGE';
const level={ demoRoute:[{kind:'move',target:[1,0,0]},{kind:'interact',treasureId:'a'},{kind:'exit'}], treasures:[{id:'a',approach:[1,0,0]}], exit:{position:[2,0,0]} };
const session={getSnapshot:()=>({state,treasures:[{id:'a',state:treasure}]})};
const p=(x=0)=>({position:{x,y:0,z:0},grounded:true,controlLocked:false});
const d=createDemoController({level,session});
d.reset(); let f=d.readFrame(p(),0,.1); assert(f.moveX>0); assert(Math.abs(f.moveY)<1e-10);
f=d.readFrame(p(),Math.PI/2,.1); assert(Math.abs(f.moveX)<1e-10); assert(f.moveY<0);
const before=d.getSnapshot(); state='PAUSED'; d.readFrame(p(),0,50); assert.deepEqual(d.getSnapshot(),before); state='PLAYING';
d.readFrame(p(1),0,.1); assert.equal(d.getSnapshot().index,1);
assert(d.readFrame(p(1),0,.1).interactPressed); assert(!d.readFrame(p(1),0,.1).interactPressed);
treasure='COLLECTING'; assert(!d.readFrame(p(1),0,.1).interactPressed); treasure='COLLECTED'; d.readFrame(p(1),0,.1); assert.equal(d.getSnapshot().index,2);
state='WIN'; d.readFrame(p(2),0,.1); assert.equal(d.getSnapshot().outcome,'won');
state='PLAYING'; d.reset(); d.readFrame(p(),0,23); assert.equal(d.getSnapshot().outcome,'failed');
d.reset(); d.readFrame(p(),0,GAME_RULES.demoTimeout+1); assert(d.getSnapshot().failure.includes('总时限'));
d.reset(); d.stop(); assert.equal(d.readFrame(p(),0,1).moveX,0); assert.equal(d.getSnapshot().outcome,'stopped');
d.reset(); state='GAME_OVER'; d.readFrame(p(),0,.1); assert.equal(d.getSnapshot().outcome,'failed');
state='PLAYING'; d.reset(); const initial=d.getSnapshot(); d.readFrame(p(),0,NaN); assert.deepEqual(d.getSnapshot(),initial);
const empty=createDemoController({level:{...level,demoRoute:[]},session}); empty.reset(); assert.equal(empty.getSnapshot().outcome,'failed');
console.log('PASS Demo controller: camera transform, pause freeze, real-state waiting, edge inputs, terminal states, stop/restart, step/global timeout, empty route, invalid dt');
